SELECT
    CAST(FL_DATE AS DATE) AS flight_date,
    TRIM(AIRLINE) AS carrier_name,
    TRIM(AIRLINE_DOT) AS airline_dot,
    TRIM(AIRLINE_CODE) AS carrier_code,
    CAST(DOT_CODE AS INTEGER) AS dot_code,
    CAST(FL_NUMBER AS INTEGER) AS flight_number,
    TRIM(ORIGIN) AS origin_code,
    TRIM(ORIGIN_CITY) AS origin_city,
    TRIM(DEST) AS dest_code,
    TRIM(DEST_CITY) AS dest_city,
    CAST(CRS_DEP_TIME AS INTEGER) AS crs_dep_time,
    CAST(DEP_TIME AS DOUBLE) AS dep_time,
    CAST(DEP_DELAY AS DOUBLE) AS dep_delay,
    CAST(TAXI_OUT AS DOUBLE) AS taxi_out,
    CAST(WHEELS_OFF AS DOUBLE) AS wheels_off,
    CAST(WHEELS_ON AS DOUBLE) AS wheels_on,
    CAST(TAXI_IN AS DOUBLE) AS taxi_in,
    CAST(CRS_ARR_TIME AS INTEGER) AS crs_arr_time,
    CAST(ARR_TIME AS DOUBLE) AS arr_time,
    CAST(ARR_DELAY AS DOUBLE) AS arr_delay,
    COALESCE(CAST(CANCELLED AS INTEGER), 0) AS cancelled,
    NULLIF(TRIM(CANCELLATION_CODE), '') AS cancellation_code,
    COALESCE(CAST(DIVERTED AS INTEGER), 0) AS diverted,
    CAST(CRS_ELAPSED_TIME AS DOUBLE) AS crs_elapsed_time,
    CAST(ELAPSED_TIME AS DOUBLE) AS elapsed_time,
    CAST(AIR_TIME AS DOUBLE) AS air_time,
    CAST(DISTANCE AS DOUBLE) AS distance,
    CAST(DELAY_DUE_CARRIER AS DOUBLE) AS delay_due_carrier,
    CAST(DELAY_DUE_WEATHER AS DOUBLE) AS delay_due_weather,
    CAST(DELAY_DUE_NAS AS DOUBLE) AS delay_due_nas,
    CAST(DELAY_DUE_SECURITY AS DOUBLE) AS delay_due_security,
    CAST(DELAY_DUE_LATE_AIRCRAFT AS DOUBLE) AS delay_due_late_aircraft
FROM read_csv_auto(
    '{{ env_var("BI_RAW_CSV", "/data/raw/flights_sample_3m.csv") }}',
    header = true,
    sample_size = 200000,
    types = {
        'FL_DATE': 'DATE',
        'AIRLINE': 'VARCHAR',
        'AIRLINE_DOT': 'VARCHAR',
        'AIRLINE_CODE': 'VARCHAR',
        'DOT_CODE': 'INTEGER',
        'FL_NUMBER': 'INTEGER',
        'ORIGIN': 'VARCHAR',
        'ORIGIN_CITY': 'VARCHAR',
        'DEST': 'VARCHAR',
        'DEST_CITY': 'VARCHAR',
        'CRS_DEP_TIME': 'INTEGER',
        'DEP_TIME': 'DOUBLE',
        'DEP_DELAY': 'DOUBLE',
        'TAXI_OUT': 'DOUBLE',
        'WHEELS_OFF': 'DOUBLE',
        'WHEELS_ON': 'DOUBLE',
        'TAXI_IN': 'DOUBLE',
        'CRS_ARR_TIME': 'INTEGER',
        'ARR_TIME': 'DOUBLE',
        'ARR_DELAY': 'DOUBLE',
        'CANCELLED': 'DOUBLE',
        'CANCELLATION_CODE': 'VARCHAR',
        'DIVERTED': 'DOUBLE',
        'CRS_ELAPSED_TIME': 'DOUBLE',
        'ELAPSED_TIME': 'DOUBLE',
        'AIR_TIME': 'DOUBLE',
        'DISTANCE': 'DOUBLE',
        'DELAY_DUE_CARRIER': 'DOUBLE',
        'DELAY_DUE_WEATHER': 'DOUBLE',
        'DELAY_DUE_NAS': 'DOUBLE',
        'DELAY_DUE_SECURITY': 'DOUBLE',
        'DELAY_DUE_LATE_AIRCRAFT': 'DOUBLE'
    }
)
WHERE FL_DATE IS NOT NULL
